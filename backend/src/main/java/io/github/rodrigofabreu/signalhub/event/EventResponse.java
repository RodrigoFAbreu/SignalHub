package io.github.rodrigofabreu.signalhub.event;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonRawValue;
import io.github.rodrigofabreu.signalhub.api.QuestionState;
import java.time.Instant;
import java.util.UUID;
import org.eclipse.microprofile.openapi.annotations.media.Schema;

/** The canonical representation of a stored event, as returned by the API. */
@Schema(name = "Event", description = "A stored event in its canonical form.")
public record EventResponse(
    @Schema(
            required = true,
            description = "Canonical event ID, generated by SignalHub (UUIDv7).",
            examples = "01997d5e-8a3c-7b1e-9f2a-4c6d8e0f1a2b")
        UUID id,
    @Schema(
            required = true,
            description =
                "The producer that published the event, as authenticated by its API key. Never"
                    + " taken from the request body.")
        Producer producer,
    @Schema(examples = "signalhub") String context,
    @Schema(required = true) Category category,
    @Schema(required = true) Severity severity,
    @Schema(required = true, examples = "Nightly build failed") String title,
    @Schema(examples = "3 of 412 tests failed on main.") String message,
    @Schema(
            required = true,
            ref = "JsonObject",
            description = "Producer metadata as submitted; an empty object when none was sent.")
        // Already-valid JSON text from PostgreSQL, written into the response as is.
        @JsonRawValue
        String metadata,
    @Schema(
            description =
                "URL the owner can open from the event, as the producer sent it; null if it sent"
                    + " none.",
            examples = "https://ci.example.com/runs/1842",
            nullable = true)
        String link,
    @Schema(
            description = "Producer-supplied occurrence time, normalized to UTC; null if not sent.",
            examples = "2026-09-25T12:03:00Z")
        Instant occurredAt,
    @Schema(
            required = true,
            description = "Canonical time SignalHub accepted and stored the event, in UTC.",
            examples = "2026-09-25T12:03:01.482113Z")
        Instant createdAt,
    @Schema(
            description =
                "When the caller's user marked the event read, from any of their devices, in UTC; null"
                    + " while it is unread. The admin token sees the operator's own read state."
                    + " Always null in a producer's response.",
            examples = "2026-09-25T12:10:44.019273Z",
            nullable = true)
        Instant readAt,
    @Schema(
            description =
                "How the event's pushes went, from its delivery records (see the event's"
                    + " deliveries). Only in the admin token's event listing; absent everywhere"
                    + " else.")
        @JsonInclude(JsonInclude.Include.NON_NULL)
        PushSummary push,
    @Schema(
            description =
                "The question the producer asked on this event, with who can answer it; null"
                    + " when the event asks nothing.",
            nullable = true)
        AskView ask,
    @Schema(
            description = "The accepted answer; null unless answerState is ANSWERED.",
            nullable = true)
        QuestionState.Answer answer,
    @Schema(
            description =
                "OPEN, ANSWERED or CLOSED; null when the event asks nothing. CLOSED as soon as"
                    + " closesAt passes.",
            nullable = true)
        QuestionState.State answerState,
    @Schema(
            description = "Who closed the question: PRODUCER or TIME; null unless CLOSED.",
            nullable = true)
        QuestionState.ClosedBy closedBy,
    @Schema(description = "When the question closed; null unless CLOSED.", nullable = true)
        Instant closedAt,
    @Schema(description = "The producer's note on closing it, if it gave one.", nullable = true)
        String closeNote,
    @Schema(
            required = true,
            description =
                "Whether the caller may answer the question now. Always false for the admin token"
                    + " and for producers.")
        boolean canAnswer) {

  @Schema(name = "EventProducer", description = "The producer that published an event.")
  public record Producer(
      @Schema(
              required = true,
              description = "Canonical producer ID.",
              examples = "01997d5d-1c2b-7a40-8e3f-5b6c7d8e9f00")
          UUID id,
      @Schema(required = true, description = "Producer name.", examples = "ci-build-runner")
          String name) {}
}
